/**
 * The packages whose public API gets a committed report (`packages/<name>/api.md`). The
 * app is left out: nothing imports it, so its exports are not an API.
 */
export const API_PACKAGES = ['util', 'carddata', 'engine', 'scenarios'] as const;

const NOISE = [
  /^\s*\/\/ \(undocumented\)$/,
  /^\s*\/\/ @public( \(undocumented\))?$/,
  /^\/\/ \(No @packageDocumentation comment for this package\)$/,
];
const GENERATED_NOTICE = /^> Do not edit this file\..*$/m;

/**
 * Turns an API Extractor report into the committed `api.md`. API Extractor marks every
 * member without TSDoc `(undocumented)` and every export `@public`; this repo documents
 * types rather than each field and has no release tags, so both lines are noise that
 * would bury the actual signatures, and they are removed. API Extractor writes CRLF line
 * ends; the committed file uses LF like the rest of the repo.
 */
export function cleanApiReport(report: string): string {
  const lines = report
    .split(/\r?\n/)
    .filter((line) => !NOISE.some((pattern) => pattern.test(line)));
  return lines
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .replace(
      GENERATED_NOTICE,
      '> Generated by `pnpm api:report` with [API Extractor](https://api-extractor.com/); do not edit. ' +
        'A change here is a change to what other packages can use.',
    );
}
